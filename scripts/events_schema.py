#!/usr/bin/env python3
"""Generate or verify events.schema.json from the contract's event specs.

The event specs are the `#[contractevent]` structs in `src/events.rs`. This
script parses that file (no Rust toolchain needed) and writes a deterministic
JSON schema of every event: its topic symbol, struct name, data format and the
ordered data fields with their Soroban types. Standard library only.

Usage:
  scripts/events_schema.py           write events.schema.json
  scripts/events_schema.py --check   fail if events.schema.json is stale
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
EVENTS_RS = ROOT / "src" / "events.rs"
SCHEMA = ROOT / "events.schema.json"

SCHEMA_VERSION = 1

EVENT_RE = re.compile(
    r"#\[contractevent\((?P<attrs>[^\]]*)\)\]\s*pub struct (?P<name>\w+) \{(?P<body>[^}]*)\}",
    re.S,
)
TOPIC_RE = re.compile(r'topics\s*=\s*\[\s*"(?P<topic>[^"]+)"\s*\]')
FORMAT_RE = re.compile(r'data_format\s*=\s*"(?P<format>[^"]+)"')
FIELD_RE = re.compile(r"pub (?P<field>\w+): (?P<type>[\w:<>]+)")


def parse_events(source: str) -> list[dict]:
    events = []
    for match in EVENT_RE.finditer(source):
        attrs = match.group("attrs")
        topic = TOPIC_RE.search(attrs)
        data_format = FORMAT_RE.search(attrs)
        if topic is None or data_format is None:
            raise ValueError(f"event {match.group('name')} is missing topics or data_format")
        fields = [
            {"name": f.group("field"), "type": f.group("type")}
            for f in FIELD_RE.finditer(match.group("body"))
        ]
        events.append(
            {
                "topic": topic.group("topic"),
                "struct": match.group("name"),
                "data_format": data_format.group("format"),
                "fields": fields,
            }
        )
    if not events:
        raise ValueError(f"no #[contractevent] structs found in {EVENTS_RS}")
    return events


def build_schema(source: str) -> dict:
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://github.com/D-Indexer/Indexer-Contract/events.schema.json",
        "title": "Indexer Contract events",
        "description": (
            "Machine-readable schema of the contract events emitted by src/events.rs. "
            "Generated by scripts/events_schema.py; do not edit by hand."
        ),
        "schema_version": SCHEMA_VERSION,
        "source": "src/events.rs",
        "encoding": {
            "topics": "topics[0] is the event topic Symbol; no data fields are in topics",
            "data": "ScVal::Vec of the fields below, in order (data_format = \"vec\")",
            "compatibility": "fields are only appended; topic symbols are never renamed",
        },
        "events": parse_events(source),
    }


def render(schema: dict) -> str:
    return json.dumps(schema, indent=2) + "\n"


def main(argv: list[str]) -> int:
    generated = render(build_schema(EVENTS_RS.read_text()))
    if argv[1:] == ["--check"]:
        current = SCHEMA.read_text() if SCHEMA.exists() else ""
        if current != generated:
            print(
                f"{SCHEMA.name} is out of date; run scripts/events_schema.py",
                file=sys.stderr,
            )
            return 1
        print(f"ok {SCHEMA.name}")
        return 0
    if argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    SCHEMA.write_text(generated)
    print(f"wrote {SCHEMA.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
