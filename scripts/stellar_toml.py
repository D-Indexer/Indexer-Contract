#!/usr/bin/env python3
"""Generate and verify the Folder contract section of the project's stellar.toml.

SEP-1 (v2.7.0) only defines contract IDs inside [[CURRENCIES]] (and for SEP-45
web auth), so the contract is published as a [[FOLDER_CONTRACTS]] extension
table, one per network. SEP-1 parsers ignore unknown keys. Configuration (home
domain, links) lives in stellar-toml.config.json. Standard library only.

Usage:
  scripts/stellar_toml.py generate [--check]   write (or check) stellar.toml.fragment
  scripts/stellar_toml.py verify [--url URL]   compare the published stellar.toml
                                               with deployments/*.json
"""
import argparse
import json
import pathlib
import sys
import tomllib
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONFIG = ROOT / "stellar-toml.config.json"
DEPLOYMENTS = ROOT / "deployments"
FRAGMENT = ROOT / "stellar.toml.fragment"
TABLE = "FOLDER_CONTRACTS"
# Fields copied from each deployment record, in output order.
FIELDS = ("network", "network_passphrase", "contract_id", "wasm_hash", "source_commit")


def load_config(path=CONFIG):
    return json.loads(pathlib.Path(path).read_text())


def load_deployments(directory=DEPLOYMENTS):
    return [json.loads(p.read_text()) for p in sorted(pathlib.Path(directory).glob("*.json"))]


def expected_entries(deployments, config):
    return [
        {
            **{f: d[f] for f in FIELDS},
            "source_repository": config["source_repository"],
            "documentation": config["documentation"],
        }
        for d in sorted(deployments, key=lambda d: d["network"])
    ]


def toml_string(value):
    return json.dumps(value, ensure_ascii=False)  # JSON strings are valid TOML basic strings


def render(deployments, config):
    lines = [
        "# Folder contract deployments. Generated by scripts/stellar_toml.py from",
        "# deployments/*.json; do not edit by hand. Paste into the project's",
        "# /.well-known/stellar.toml. SEP-1 v2.7.0 has no contract table outside",
        f"# [[CURRENCIES]], so [[{TABLE}]] is an extension that SEP-1 parsers ignore.",
    ]
    for entry in expected_entries(deployments, config):
        lines += ["", f"[[{TABLE}]]"]
        lines += [f"{key} = {toml_string(value)}" for key, value in entry.items()]
    return "\n".join(lines) + "\n"


def compare(published_toml, deployments, config):
    """Returns a list of human-readable mismatches (empty when in sync)."""
    try:
        published = tomllib.loads(published_toml).get(TABLE, [])
    except tomllib.TOMLDecodeError as err:
        return [f"stellar.toml does not parse: {err}"]
    by_network = {e.get("network"): e for e in published}
    problems = []
    for want in expected_entries(deployments, config):
        got = by_network.pop(want["network"], None)
        if got is None:
            problems.append(f"{want['network']}: missing from [[{TABLE}]]")
            continue
        for key, value in want.items():
            if got.get(key) != value:
                problems.append(f"{want['network']}: {key} is {got.get(key)!r}, expected {value!r}")
    problems += [f"{net}: published but has no deployment record" for net in by_network]
    return problems


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "stellar-toml-verify"})
    with urllib.request.urlopen(request, timeout=20) as response:
        return response.read().decode()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--check", action="store_true", help="fail if the fragment is stale")
    ver = sub.add_parser("verify")
    ver.add_argument("--url", help="override https://<home_domain>/.well-known/stellar.toml")
    args = parser.parse_args(argv)

    config, deployments = load_config(), load_deployments()
    if args.command == "generate":
        text = render(deployments, config)
        if args.check:
            if not FRAGMENT.exists() or FRAGMENT.read_text() != text:
                print(f"{FRAGMENT.name} is stale; run scripts/stellar_toml.py generate")
                return 1
            print(f"{FRAGMENT.name} is up to date")
            return 0
        FRAGMENT.write_text(text)
        print(f"wrote {FRAGMENT.name}")
        return 0

    url = args.url
    if not url:
        if not config.get("home_domain"):
            print(f"set home_domain in {CONFIG.name} (or pass --url)")
            return 2
        url = f"https://{config['home_domain']}/.well-known/stellar.toml"
    problems = compare(fetch(url), deployments, config)
    for problem in problems:
        print(f"MISMATCH {problem}")
    if not problems:
        print(f"ok: {url} lists the current deployments")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
